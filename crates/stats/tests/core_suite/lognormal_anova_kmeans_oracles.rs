// 9. Verifier Audit Regression Tests (Frey, RM Diagonal Pooling, 3-Way RM,
//    Multi-Slice Tukey, K-Means ANOVA Validation, Unbounded REML LRT)
// ============================================================================

#[test]
fn regression_rm_diagonal_pooling_and_two_factor_tukey_multi_slice() {
    // 1. RM 2-way diagonal cell pair (ra != rb && ca != cb) error pooling for RowFactorMatched & BothFactorsMatched.
    let s_count = 6_usize;
    let mut entries = Vec::new();
    let mut subj_data = vec![vec![vec![0.0_f64; 3]; 3]; s_count];
    for s in 0..s_count {
        for r in 0..3 {
            for c in 0..3 {
                let sf = s as f64;
                let rf = r as f64;
                let cf = c as f64;
                // Distinct variance across Subject, Subject×Row, Subject×Col, and residual interactions.
                let v = 10.0
                    + 2.5 * rf
                    + 1.8 * cf
                    + 0.7 * rf * cf
                    + 1.3 * (sf - 2.5)
                    + (if r == 1 { 0.9 } else { -0.45 }) * (sf - 2.5)
                    + (if c == 2 { 1.1 } else { -0.55 }) * (sf - 2.5)
                    + ((s * 7 + r * 3 + c * 5) % 5) as f64 * 0.17;
                subj_data[s][r][c] = v;
                entries.push((s, c, r, v));
            }
        }
    }
    let sheet_rm = grouped_sheet_entries("rm_diag", "Row", "Col", &["R1", "R2", "R3"], &["C1", "C2", "C3"], s_count, &entries);

    // RowFactorMatched (A within, B between): pooled MS = (MS_{S(B)} + (a - 1)*MS_{A×S(B)}) / a
    let rm_row_fit =
        fit_rm_two_way_anova_with_sphericity(&subj_data, "Row", "Col", RepeatedMeasuresDesign::RowFactorMatched, RmSphericityCorrection::None)
            .unwrap();
    let res_row = run_kind(
        &sheet_rm,
        AnalysisKind::FactorialAnova(FactorialAnovaSpec {
            repeated_measures: RepeatedMeasuresDesign::RowFactorMatched,
            comparison_family_mode: FactorialComparisonFamilyMode::PreselectedPairs,
            preselected_pairs: vec![(0, 4)], // (0,0) vs (1,1) diagonal cell pair
            multiplicity: MultiplicitySpec { method: MultiplicityMethod::Bonferroni, ..MultiplicitySpec::default() },
            ..FactorialAnovaSpec::default()
        }),
    )
    .unwrap();
    let mc_row = tab_by_id(&res_row, "multiple-comparisons-preselected");
    let ms_sb = rm_row_fit.anova.terms[1].ms / rm_row_fit.anova.terms[1].f_statistic.unwrap();
    let ms_asb = rm_row_fit.anova.ms_residual;
    let df_sb = rm_row_fit.term_error_dfs[1];
    let df_asb = rm_row_fit.term_error_dfs[2];
    let expected_se_row = (2.0 * ((ms_sb + 2.0 * ms_asb) / 3.0) / (s_count as f64)).sqrt();
    let t1_r = ms_sb;
    let t2_r = 2.0 * ms_asb;
    let expected_df_row = (t1_r + t2_r).powi(2) / (t1_r * t1_r / df_sb + t2_r * t2_r / df_asb);
    assert_approx_eq(cell_num(&mc_row.rows[0][1]), expected_se_row, 1e-10, 1e-10, "RowFactorMatched diagonal SE");
    assert_approx_eq(cell_num(&mc_row.rows[0][3]), expected_df_row, 1e-10, 1e-10, "RowFactorMatched diagonal df");

    // BothFactorsMatched: Var = (2/S) * ((1/b)*MS_SA + (1/a)*MS_SB + (1 - 1/a - 1/b)*MS_SAB)
    let rm_both_fit =
        fit_rm_two_way_anova_with_sphericity(&subj_data, "Row", "Col", RepeatedMeasuresDesign::BothFactorsMatched, RmSphericityCorrection::None)
            .unwrap();
    let res_both = run_kind(
        &sheet_rm,
        AnalysisKind::FactorialAnova(FactorialAnovaSpec {
            repeated_measures: RepeatedMeasuresDesign::BothFactorsMatched,
            comparison_family_mode: FactorialComparisonFamilyMode::PreselectedPairs,
            preselected_pairs: vec![(0, 4)],
            multiplicity: MultiplicitySpec { method: MultiplicityMethod::Bonferroni, ..MultiplicitySpec::default() },
            ..FactorialAnovaSpec::default()
        }),
    )
    .unwrap();
    let mc_both = tab_by_id(&res_both, "multiple-comparisons-preselected");
    let ms_sa = rm_both_fit.anova.terms[0].ms / rm_both_fit.anova.terms[0].f_statistic.unwrap();
    let ms_sb2 = rm_both_fit.anova.terms[1].ms / rm_both_fit.anova.terms[1].f_statistic.unwrap();
    let ms_sab = rm_both_fit.anova.ms_residual;
    let df_sa = rm_both_fit.term_error_dfs[0];
    let df_sb2 = rm_both_fit.term_error_dfs[1];
    let df_sab = rm_both_fit.term_error_dfs[2];
    let w_a = ms_sa / 3.0;
    let w_b = ms_sb2 / 3.0;
    let w_ab = (1.0 - 2.0 / 3.0) * ms_sab;
    let expected_se_both = (2.0 * (w_a + w_b + w_ab) / (s_count as f64)).sqrt();
    let expected_df_both = (w_a + w_b + w_ab).powi(2) / (w_a * w_a / df_sa + w_b * w_b / df_sb2 + w_ab * w_ab / df_sab);
    assert_approx_eq(cell_num(&mc_both.rows[0][1]), expected_se_both, 1e-10, 1e-10, "BothFactorsMatched diagonal SE");
    assert_approx_eq(cell_num(&mc_both.rows[0][3]), expected_df_both, 1e-10, 1e-10, "BothFactorsMatched diagonal df");

    // 2. TwoFactorFamilies with TukeyHsd must adjust across all n_slices slices via max_studentized_range_sf
    //    and therefore be strictly more conservative than PerSliceFamilies on the 3x3 table.
    let root = oracle_root();
    let ofd = root.get("r23_4_anova_kmeans_power").get("two_way_one_factor_diff");
    let mut entries_3x3 = Vec::new();
    for (r, r_lbl) in ["R1", "R2", "R3"].iter().enumerate() {
        for (c, c_lbl) in ["C1", "C2", "C3"].iter().enumerate() {
            let key = format!("{r_lbl}:{c_lbl}");
            for (s, &v) in json_f64_vec(ofd.get("cells").get(&key)).iter().enumerate() {
                entries_3x3.push((s, c, r, v));
            }
        }
    }
    let sheet_3x3 = grouped_sheet_entries("f2_tukey", "Row", "Col", &["R1", "R2", "R3"], &["C1", "C2", "C3"], 4, &entries_3x3);
    let r_2fam_tukey = run_kind(
        &sheet_3x3,
        AnalysisKind::FactorialAnova(FactorialAnovaSpec {
            comparison_family_mode: FactorialComparisonFamilyMode::TwoFactorFamilies,
            multiplicity: MultiplicitySpec { method: MultiplicityMethod::TukeyHsd, ..MultiplicitySpec::default() },
            ..FactorialAnovaSpec::default()
        }),
    )
    .unwrap();
    let r_slice_tukey = run_kind(
        &sheet_3x3,
        AnalysisKind::FactorialAnova(FactorialAnovaSpec {
            comparison_family_mode: FactorialComparisonFamilyMode::PerSliceFamilies,
            multiplicity: MultiplicitySpec { method: MultiplicityMethod::TukeyHsd, ..MultiplicitySpec::default() },
            ..FactorialAnovaSpec::default()
        }),
    )
    .unwrap();
    let tab_2fam = tab_by_id(&r_2fam_tukey, "multiple-comparisons-family-factor-2");
    let tab_slice = tab_by_id(&r_slice_tukey, "multiple-comparisons-per-slice-factor-2");
    assert_eq!(tab_2fam.rows.len(), tab_slice.rows.len());
    let mut any_strictly_larger = false;
    for (row_2, row_s) in tab_2fam.rows.iter().zip(tab_slice.rows.iter()) {
        let q = cell_num(&row_2[2]);
        let df = cell_num(&row_2[3]);
        let p_2 = cell_p(&row_2[5]);
        let p_s = cell_p(&row_s[5]);
        let expected_p2 = curvebook_math::dist::max_studentized_range_sf(q, 3, 3, df).unwrap();
        assert_approx_eq(p_2, expected_p2, 1e-12, 1e-12, "TwoFactorFamilies Tukey max_studentized_range_sf");
        assert!(p_2 >= p_s - 1e-15, "TwoFactorFamilies p ({p_2}) must be >= PerSliceFamilies p ({p_s})");
        if p_s > 1e-12 && p_s < 0.99 {
            assert!(p_2 > p_s, "TwoFactorFamilies Tukey p ({p_2}) must be strictly more conservative than PerSliceFamilies ({p_s})");
            any_strictly_larger = true;
        }
    }
    assert!(any_strictly_larger, "expected at least one non-saturated comparison to confirm strict conservatism");
}

#[test]
fn regression_three_way_rm_unstructured_mv_guard_kmeans_anova_and_unbounded_lrt() {
    // 1. Three-way GroupedTable with three_way_rm_factors: Some([true, false, false]) + ResidualCovariance::Unstructured
    //    must partition bet_axes = [B, Row] (clusters) vs wth_axes = [A] (2 timepoints), yielding a 2x2 covariance matrix.
    let s_n = 5_usize;
    let mut g_entries = Vec::new();
    for s in 0..s_n {
        for r in 0..2 {
            for c in 0..4 {
                let a = c / 2;
                let b = c % 2;
                let y = 12.0 + 3.0 * (a as f64) + 1.5 * (b as f64) - 0.8 * (r as f64) + 0.9 * (s as f64) + ((s * 5 + r * 3 + c) % 4) as f64 * 0.25;
                g_entries.push((s, c, r, y));
            }
        }
    }
    let sheet_3w = grouped_sheet_entries("rm3_unstr", "RowC", "ColAB", &["C1", "C2"], &["A1:B1", "A1:B2", "A2:B1", "A2:B2"], s_n, &g_entries);
    let r_unstr = run_kind(
        &sheet_3w,
        AnalysisKind::FactorialAnova(FactorialAnovaSpec {
            three_way: true,
            repeated_measures: RepeatedMeasuresDesign::None,
            three_way_rm_factors: Some([true, false, false]),
            residual_covariance: ResidualCovariance::Unstructured,
            ..FactorialAnovaSpec::default()
        }),
    )
    .unwrap();
    assert_all_sheet_numbers_finite(&r_unstr, "3-way Unstructured REML [true, false, false]");
    let cov_tab = tab_by_id(&r_unstr, "unstructured-reml-covariance");
    assert_eq!(cov_tab.rows.len(), 2, "Unstructured REML for [true, false, false] must fit 2x2 timepoint covariance (Factor A only)");

    // 2. Unbalanced MultipleVariablesTable with three_way_rm_factors active must return Err (never silent OLS fallback).
    let mut col_a = Vec::new();
    let mut col_b = Vec::new();
    let mut col_c = Vec::new();
    let mut col_y = Vec::new();
    for s in 0..3 {
        for a in 0..2 {
            for b in 0..2 {
                for c in 0..2 {
                    if s == 2 && a == 1 && b == 1 && c == 1 {
                        continue; // Make one cell unbalanced (2 instead of 3 replicates)
                    }
                    col_a.push(Cell::text(format!("A{}", a + 1)));
                    col_b.push(Cell::text(format!("B{}", b + 1)));
                    col_c.push(Cell::text(format!("C{}", c + 1)));
                    col_y.push(Cell::number(10.0 + (s + a + b + c) as f64));
                }
            }
        }
    }
    let mv_unbal = mv_cells_sheet(
        "mv_3w_unbal",
        &[
            ("A", Some(VariableRole::Categorical), &col_a),
            ("B", Some(VariableRole::Categorical), &col_b),
            ("C", Some(VariableRole::Categorical), &col_c),
            ("Y", Some(VariableRole::Continuous), &col_y),
        ],
    );
    let err_unbal = run_kind(
        &mv_unbal,
        AnalysisKind::FactorialAnova(FactorialAnovaSpec {
            three_way: true,
            multifactor_columns: vec![0, 1, 2],
            response_column: Some(3),
            three_way_rm_factors: Some([true, false, false]),
            ..FactorialAnovaSpec::default()
        }),
    );
    assert!(matches!(err_unbal, Err(StatsError::IncompatibleAnalysisSpec { .. })), "unbalanced MV 3-way RM must error, got {err_unbal:?}");

    // 3. kmeans_feature_anova must return Err on malformed inputs without panicking or propagating NaN.
    let good_rows = vec![vec![1.0, 2.0], vec![1.2, 2.1], vec![5.0, 6.0], vec![5.1, 6.2]];
    let labels = vec![String::from("X"), String::from("Y")];
    assert!(kmeans_feature_anova(&good_rows, &labels, &[0, 0, 1], 2).is_err(), "short assignments must err");
    assert!(kmeans_feature_anova(&good_rows, &labels, &[0, 0, 1, 2], 2).is_err(), "OOB assignment >= k must err");
    assert!(kmeans_feature_anova(&[vec![1.0, 2.0], vec![1.0], vec![5.0, 6.0], vec![5.1, 6.2]], &labels, &[0, 0, 1, 1], 2).is_err());
    assert!(kmeans_feature_anova(&[vec![1.0, f64::NAN], vec![1.2, 2.1], vec![5.0, 6.0], vec![5.1, 6.2]], &labels, &[0, 0, 1, 1], 2).is_err());
    assert!(kmeans_feature_anova(&good_rows, &labels, &[0, 0, 1, 1], 1).is_err(), "k < 2 must err");
    assert!(kmeans_feature_anova(&good_rows, &[], &[0, 0, 1, 1], 2).is_err(), "empty labels must err");

    // 4. Unbounded random-intercept REML with negative tau_hat must report two-sided chi2_sf(lrt_chi2, 1) (not 1.0).
    let neg_subj = vec![0, 0, 0, 1, 1, 1, 2, 2, 2, 3, 3, 3, 4, 4, 4];
    let neg_trt = [0, 1, 2, 0, 1, 2, 0, 1, 2, 0, 1, 2, 0, 1, 2];
    let neg_y = vec![10.0, 15.0, 20.0, 12.2, 11.2, 22.2, 7.8, 18.8, 17.8, 14.3, 13.3, 18.3, 10.7, 16.7, 16.7];
    let mut x_rows = Vec::with_capacity(neg_y.len() * 3);
    for &t in &neg_trt {
        x_rows.push(1.0);
        x_rows.push(if t == 1 { 1.0 } else { 0.0 });
        x_rows.push(if t == 2 { 1.0 } else { 0.0 });
    }
    let x_mat = DenseMatrix::from_row_major(neg_y.len(), 3, x_rows).unwrap();
    let ri_unb = fit_random_intercept_reml_with_policy(
        &x_mat,
        &neg_y,
        &neg_subj,
        &[("Treatment", 1, 2)],
        MixedModelDfMethod::Satterthwaite,
        RemlZeroVariancePolicy::Unbounded,
    )
    .unwrap();
    assert!(ri_unb.sigma2_random < 0.0 && ri_unb.lrt_random_chi2 > 0.0);
    let expected_lrt_p = curvebook_math::dist::chi2_sf(ri_unb.lrt_random_chi2, 1.0).unwrap();
    assert_approx_eq(ri_unb.lrt_random_p, expected_lrt_p, 1e-12, 1e-12, "Unbounded REML negative-tau LRT p-value");
    assert!(ri_unb.lrt_random_p < 1.0);
}
