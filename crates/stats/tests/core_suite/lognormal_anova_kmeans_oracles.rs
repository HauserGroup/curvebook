#[derive(Debug, Clone)]
pub(crate) enum JVal {
    Null,
    Bool(bool),
    Num(f64),
    Str(String),
    Arr(Vec<JVal>),
    Obj(BTreeMap<String, JVal>),
}

impl JVal {
    pub(crate) fn get(&self, key: &str) -> &JVal {
        match self {
            JVal::Obj(m) => m.get(key).unwrap_or_else(|| panic!("missing JSON key `{key}`")),
            other => panic!("expected JSON object for key `{key}`, got {other:?}"),
        }
    }

    pub(crate) fn as_f64(&self) -> Option<f64> {
        match self {
            JVal::Num(v) => Some(*v),
            _ => None,
        }
    }

    pub(crate) fn as_bool(&self) -> bool {
        match self {
            JVal::Bool(b) => *b,
            other => panic!("expected bool, got {other:?}"),
        }
    }

    pub(crate) fn as_str(&self) -> &str {
        match self {
            JVal::Str(s) => s.as_str(),
            other => panic!("expected string, got {other:?}"),
        }
    }

    pub(crate) fn as_array(&self) -> &[JVal] {
        match self {
            JVal::Arr(v) => v.as_slice(),
            other => panic!("expected array, got {other:?}"),
        }
    }

    pub(crate) fn as_object(&self) -> &BTreeMap<String, JVal> {
        match self {
            JVal::Obj(m) => m,
            other => panic!("expected object, got {other:?}"),
        }
    }
}

struct JsonParser<'a> {
    bytes: &'a [u8],
    pos: usize,
}

impl<'a> JsonParser<'a> {
    fn new(src: &'a str) -> Self {
        Self { bytes: src.as_bytes(), pos: 0 }
    }

    fn skip_ws(&mut self) {
        while self.pos < self.bytes.len() && matches!(self.bytes[self.pos], b' ' | b'\n' | b'\r' | b'\t') {
            self.pos += 1;
        }
    }

    fn parse_val(&mut self) -> JVal {
        self.skip_ws();
        match self.bytes[self.pos] {
            b'{' => self.parse_obj(),
            b'[' => self.parse_arr(),
            b'"' => JVal::Str(self.parse_str()),
            b't' => {
                self.pos += 4;
                JVal::Bool(true)
            }
            b'f' => {
                self.pos += 5;
                JVal::Bool(false)
            }
            b'n' => {
                self.pos += 4;
                JVal::Null
            }
            _ => self.parse_num(),
        }
    }

    fn parse_str(&mut self) -> String {
        self.pos += 1; // opening '"'
        let mut out = String::new();
        while self.bytes[self.pos] != b'"' {
            if self.bytes[self.pos] == b'\\' {
                self.pos += 1;
                let esc = self.bytes[self.pos];
                out.push(match esc {
                    b'n' => '\n',
                    b'r' => '\r',
                    b't' => '\t',
                    b'"' => '"',
                    b'\\' => '\\',
                    other => other as char,
                });
                self.pos += 1;
            } else {
                let start = self.pos;
                while self.pos < self.bytes.len() && self.bytes[self.pos] != b'"' && self.bytes[self.pos] != b'\\' {
                    self.pos += 1;
                }
                out.push_str(std::str::from_utf8(&self.bytes[start..self.pos]).unwrap());
            }
        }
        self.pos += 1; // closing '"'
        out
    }

    fn parse_num(&mut self) -> JVal {
        let start = self.pos;
        while self.pos < self.bytes.len() && matches!(self.bytes[self.pos], b'-' | b'+' | b'0'..=b'9' | b'.' | b'e' | b'E') {
            self.pos += 1;
        }
        let s = std::str::from_utf8(&self.bytes[start..self.pos]).unwrap();
        JVal::Num(s.parse::<f64>().unwrap())
    }

    fn parse_arr(&mut self) -> JVal {
        self.pos += 1; // '['
        let mut items = Vec::new();
        loop {
            self.skip_ws();
            if self.bytes[self.pos] == b']' {
                self.pos += 1;
                return JVal::Arr(items);
            }
            items.push(self.parse_val());
            self.skip_ws();
            if self.bytes[self.pos] == b',' {
                self.pos += 1;
            }
        }
    }

    fn parse_obj(&mut self) -> JVal {
        self.pos += 1; // '{'
        let mut map = BTreeMap::new();
        loop {
            self.skip_ws();
            if self.bytes[self.pos] == b'}' {
                self.pos += 1;
                return JVal::Obj(map);
            }
            let key = self.parse_str();
            self.skip_ws();
            assert_eq!(self.bytes[self.pos], b':');
            self.pos += 1;
            let val = self.parse_val();
            map.insert(key, val);
            self.skip_ws();
            if self.bytes[self.pos] == b',' {
                self.pos += 1;
            }
        }
    }
}

pub(crate) fn oracle_root() -> JVal {
    JsonParser::new(include_str!("../reference/r23_stats_oracles.json")).parse_val()
}

pub(crate) fn json_f64_vec(v: &JVal) -> Vec<f64> {
    v.as_array().iter().map(|x| x.as_f64().unwrap()).collect()
}

fn json_usize_vec(v: &JVal) -> Vec<usize> {
    v.as_array().iter().map(|x| x.as_f64().unwrap() as usize).collect()
}

pub(crate) fn json_f64_matrix(v: &JVal) -> Vec<Vec<f64>> {
    v.as_array().iter().map(json_f64_vec).collect()
}

pub(crate) fn f64_at(v: &JVal, key: &str) -> f64 {
    v.get(key).as_f64().unwrap_or_else(|| panic!("missing float key `{key}`"))
}

