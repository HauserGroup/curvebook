        assert_approx_eq(fit.anova.terms[0].f_statistic.unwrap(), f64_at(sp.get("between_grp"), "f"), 1e-9, 1e-9, "2w split Group F");
        assert_approx_eq(fit.anova.terms[0].p_value.unwrap(), f64_at(sp.get("between_grp"), "p_value"), 1e-9, 1e-9, "2w split Group p");
        assert_approx_eq(fit.anova.terms[1].f_statistic.unwrap(), f64_at(sp.get("within_time"), "f"), 1e-9, 1e-9, "2w split Time F");
