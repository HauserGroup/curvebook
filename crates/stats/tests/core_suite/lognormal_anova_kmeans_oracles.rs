    assert_approx_eq(ord.log_anova.r_squared, f64_at(oa.get("ordinary"), "r_squared"), 1e-10, 1e-10, "ln ord R2");

    let g_inputs: Vec<GroupComparisonInput> = ord
        .log_anova
        .group_labels
        .iter()
        .enumerate()
        .map(|(i, lbl)| GroupComparisonInput {
            index: i,
            label: lbl.clone(),
            n: ord.log_anova.group_n[i] as f64,
            mean: ord.log_anova.group_means[i],
            sd: ord.log_anova.group_sds[i],
        })
        .collect();
    let tukey =
        compare_groups_with_procedure(&g_inputs, ord.log_anova.ms_within, ord.log_anova.df_within, MultiplicityProcedure::TukeyKramer, 0.05, true)
            .unwrap();
    let bt_tukey = back_transform_pairwise_contrasts(&tukey);
    for entry in oa.get("ordinary").get("tukey_gm_ratios").as_array() {
        let pair_str = entry.get("pair").as_str();
        let mut parts = pair_str.split('-');
        let b_lbl = parts.next().unwrap();
        let a_lbl = parts.next().unwrap();
        let c = bt_tukey.iter().find(|d| d.label_a == a_lbl && d.label_b == b_lbl).unwrap();
        let (ci_lo, ci_hi) = c.geometric_mean_ratio_ci.unwrap();
        let exp_ci = json_f64_vec(entry.get("gm_ratio_ci95"));
        assert_approx_eq(1.0 / c.geometric_mean_ratio, f64_at(entry, "gm_ratio"), 1e-9, 1e-9, pair_str);
        assert_approx_eq(1.0 / ci_hi, exp_ci[0], 1e-5, 1e-5, "Tukey GMR CI lo");
        assert_approx_eq(1.0 / ci_lo, exp_ci[1], 1e-5, 1e-5, "Tukey GMR CI hi");
        assert_approx_eq(c.adjusted_p_or_q, f64_at(entry, "p_adj"), 1e-5, 1e-4, "Tukey p_adj");
    }

    let wbf = lognormal_one_way_welch_bf(&groups, ConfidenceLevel::DEFAULT_95).unwrap();
