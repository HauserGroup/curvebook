#[test]
fn oracle_normality_lognormal_battery_relative_likelihood_and_dual_qq() {
    let root = oracle_root();
    let suite = root.get("r23_2_lognormal_suite");

    for (case_name, expected_pref) in [
        ("normality_skewed_pos", Some(PreferredDistribution::Lognormal)),
        ("normality_gaussian_pos", Some(PreferredDistribution::Normal)),
        ("normality_with_nonpositive", None),
    ] {
        let case = suite.get(case_name);
        let vals = json_f64_vec(case.get("values"));
        let bat = normality_battery(&vals, 0.05).unwrap();
        assert_eq!(bat.n_impossible_nonpositive, f64_at(case, "n_impossible_nonpositive") as usize);

        let n_sw = bat.shapiro_wilk.as_ref().unwrap();
        assert_approx_eq(n_sw.statistic, f64_at(case.get("normal").get("shapiro_wilk"), "w"), 1e-6, 1e-6, "normal SW W");
        assert_approx_eq(n_sw.p_value, f64_at(case.get("normal").get("shapiro_wilk"), "p"), 1e-4, 1e-3, "normal SW p");

        let n_dp = bat.dagostino_pearson.as_ref().unwrap();
        assert_approx_eq(n_dp.statistic, f64_at(case.get("normal").get("dagostino_pearson"), "k2"), 1e-6, 1e-6, "normal DP K2");
        assert_approx_eq(n_dp.p_value, f64_at(case.get("normal").get("dagostino_pearson"), "p_value"), 1e-6, 1e-6, "normal DP p");

        let n_ad = bat.anderson_darling.as_ref().unwrap();
        assert_approx_eq(n_ad.statistic, f64_at(case.get("normal").get("anderson_darling"), "a2_star"), 1e-6, 1e-6, "normal AD A2*");
        assert_approx_eq(n_ad.p_value, f64_at(case.get("normal").get("anderson_darling"), "p_value"), 1e-5, 1e-4, "normal AD p");

        let n_ks = bat.kolmogorov_smirnov.as_ref().unwrap();
        assert_approx_eq(n_ks.statistic, f64_at(case.get("normal"), "lilliefors_d"), 1e-8, 1e-8, "normal Lilliefors D");

        assert_eq!(bat.preferred_distribution, expected_pref, "case={case_name}");

        if expected_pref.is_some() {
            let ln_sw = bat.lognormal_shapiro_wilk.as_ref().unwrap();
            assert_approx_eq(ln_sw.statistic, f64_at(case.get("lognormal").get("shapiro_wilk"), "w"), 1e-6, 1e-6, "lognormal SW W");
            assert_approx_eq(ln_sw.p_value, f64_at(case.get("lognormal").get("shapiro_wilk"), "p"), 1e-4, 1e-3, "lognormal SW p");

            let ln_dp = bat.lognormal_dagostino_pearson.as_ref().unwrap();
            assert_approx_eq(ln_dp.statistic, f64_at(case.get("lognormal").get("dagostino_pearson"), "k2"), 1e-6, 1e-6, "lognormal DP K2");
            assert_approx_eq(ln_dp.p_value, f64_at(case.get("lognormal").get("dagostino_pearson"), "p_value"), 1e-6, 1e-6, "lognormal DP p");

            let ln_ad = bat.lognormal_anderson_darling.as_ref().unwrap();
            assert_approx_eq(ln_ad.statistic, f64_at(case.get("lognormal").get("anderson_darling"), "a2_star"), 1e-6, 1e-6, "lognormal AD A2*");
            assert_approx_eq(ln_ad.p_value, f64_at(case.get("lognormal").get("anderson_darling"), "p_value"), 1e-5, 1e-4, "lognormal AD p");

            let ln_ks = bat.lognormal_kolmogorov_smirnov.as_ref().unwrap();
            assert_approx_eq(ln_ks.statistic, f64_at(case.get("lognormal"), "lilliefors_d"), 1e-8, 1e-8, "lognormal Lilliefors D");

            let cmp = case.get("comparison");
            assert_approx_eq(bat.ll_normal.unwrap(), f64_at(cmp, "ll_normal"), 1e-9, 1e-9, "ll_normal");
            assert_approx_eq(bat.ll_lognormal.unwrap(), f64_at(cmp, "ll_lognormal"), 1e-9, 1e-9, "ll_lognormal");
            assert_approx_eq(bat.normal_vs_lognormal_lr.unwrap(), f64_at(cmp, "lr_norm_over_lognorm"), 1e-9, 1e-7, "LR(N/LN)");
            assert_approx_eq(bat.lognormal_vs_normal_lr.unwrap(), f64_at(cmp, "lr_lognorm_over_norm"), 1e-7, 1e-7, "LR(LN/N)");
            assert_approx_eq(bat.prob_normal.unwrap(), f64_at(cmp, "prob_normal"), 1e-9, 1e-7, "P(Normal)");
            assert_approx_eq(bat.prob_lognormal.unwrap(), f64_at(cmp, "prob_lognormal"), 1e-9, 1e-7, "P(Lognormal)");
        } else {
            assert!(bat.lognormal_shapiro_wilk.is_none());
            assert!(bat.lognormal_dagostino_pearson.is_none());
            assert!(bat.lognormal_anderson_darling.is_none());
            assert!(bat.lognormal_kolmogorov_smirnov.is_none());
            assert!(bat.prob_normal.is_none());
        }
    }

    // End-to-end DescriptiveSpec sheet test: normality_only + dual Blom Q-Q tabs.
    let skewed = json_f64_vec(suite.get("normality_skewed_pos").get("values"));
    let nonpos = json_f64_vec(suite.get("normality_with_nonpositive").get("values"));
    let sheet = col_sheet("norm_dual", &[("Skewed", &skewed), ("Mixed", &nonpos)]);
    let desc = DescriptiveSpec { run_normality_battery: true, normality_only: true, emit_qq_tabs: true, ..DescriptiveSpec::default() };
    let res = run_kind(&sheet, AnalysisKind::DescriptiveStats(desc)).unwrap();
    assert_all_sheet_numbers_finite(&res, "normality_only");
    assert_diagnostics_only(&res, "normality_only");

    assert!(res.tabs.iter().all(|t| t.id != "desc-summary"));
    let norm_tab = tab_by_id(&res, "normality");
    assert_approx_eq(cell_num(row_cell(norm_tab, "Number of impossible (<=0)", 0)), 0.0, 1e-12, 0.0, "impossible col 0");
    assert_approx_eq(cell_num(row_cell(norm_tab, "Number of impossible (<=0)", 1)), 2.0, 1e-12, 0.0, "impossible col 1");
    assert_eq!(cell_text(row_cell(norm_tab, "Preferred distribution", 0)), "Lognormal");
    assert_approx_eq(
        cell_num(row_cell(norm_tab, "P(Lognormal)", 0)),
        f64_at(suite.get("normality_skewed_pos").get("comparison"), "prob_lognormal"),
        1e-7,
        1e-7,
        "P(Lognormal)",
    );
    for row_lbl in ["Lognormal D'Agostino-Pearson K2", "Lognormal Anderson-Darling A2*", "Lognormal Shapiro-Wilk W", "Lognormal Kolmogorov-Smirnov D"]
    {
        assert!(cell_num(row_cell(norm_tab, row_lbl, 0)).is_finite(), "missing/non-finite `{row_lbl}`");
    }

    let qq_norm = tab_by_id(&res, "normal-qq");
    let exp_norm = json_f64_vec(suite.get("normality_skewed_pos").get("normal").get("qq").get("expected"));
    for (r, &expected_q) in exp_norm.iter().enumerate() {
        assert_approx_eq(cell_num(&qq_norm.rows[r][2]), expected_q, 1e-9, 1e-9, "Normal Q-Q expected");
    }
    let qq_ln = tab_by_id(&res, "lognormal-qq");
    let exp_ln = json_f64_vec(suite.get("normality_skewed_pos").get("lognormal").get("qq_log_space").get("expected"));
    for (r, &expected_q) in exp_ln.iter().enumerate() {
        assert_approx_eq(cell_num(&qq_ln.rows[r][2]), expected_q, 1e-9, 1e-9, "Lognormal Q-Q expected");
    }
}

