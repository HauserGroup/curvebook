fn json_str_vec(v: &JVal) -> Vec<String> {
    v.as_array().iter().map(|x| x.as_str().to_owned()).collect()
}

fn explicit_levels(levels: &[&str]) -> LevelOrderSpec {
    LevelOrderSpec { order: LevelOrderKind::Explicit(levels.iter().map(|s| (*s).to_owned()).collect()), reversed: false }
}

fn make_glm_mv_sheet(id: &str, x1: &[f64], x2: &[f64], grp: &[String], w_custom: Option<&[f64]>, y: &[Option<f64>], grp_order: &[&str]) -> DataSheet {
    let n = x1.len();
    let ncols = if w_custom.is_some() { 5 } else { 4 };
    let mut mv = MultipleVariablesTable::new(ncols, n).unwrap();
    mv.variables[0].title = String::from("x1");
    mv.variables[1].title = String::from("x2");
    mv.variables[2].title = String::from("grp");
    mv.variables[2].lock_role(VariableRole::Categorical);
    mv.variables[2].level_order = explicit_levels(grp_order);
    let y_col = if let Some(w) = w_custom {
        mv.variables[3].title = String::from("w_custom");
        for (r, &wv) in w.iter().enumerate() {
            mv.variables[3].cells[r] = Cell::number(wv);
        }
        4
    } else {
        3
    };
    mv.variables[y_col].title = String::from("y");
    for r in 0..n {
        mv.variables[0].cells[r] = Cell::number(x1[r]);
        mv.variables[1].cells[r] = Cell::number(x2[r]);
        mv.variables[2].cells[r] = Cell::text(grp[r].as_str());
        mv.variables[y_col].cells[r] = y[r].map_or_else(Cell::empty, Cell::number);
    }
    DataSheet::new(SheetId::new(id), id, TableArchetype::MultipleVariables(mv)).unwrap()
}

fn assert_lm_params_match(res: &curvebook_doc::ResultSheet, oracle: &JVal, tol: f64, label: &str) {
    let params = tab_by_id(res, "glm-linear-params");
    let beta = json_f64_vec(oracle.get("beta"));
    let se = json_f64_vec(oracle.get("se"));
    let t_vals = json_f64_vec(oracle.get("t"));
    let p_vals = json_f64_vec(oracle.get("p"));
    let lo = json_f64_vec(oracle.get("ci95_lo"));
    let hi = json_f64_vec(oracle.get("ci95_hi"));
    assert_eq!(params.rows.len(), beta.len(), "{label}: row count");
    for j in 0..beta.len() {
        assert_approx_eq(cell_num(&params.rows[j][0]), beta[j], tol, tol, &format!("{label} beta[{j}]"));
        assert_approx_eq(cell_num(&params.rows[j][1]), se[j], tol, tol, &format!("{label} se[{j}]"));
        assert_approx_eq(cell_num(&params.rows[j][2]), t_vals[j], tol, tol, &format!("{label} t[{j}]"));
        assert_approx_eq(cell_p(&params.rows[j][3]), p_vals[j], tol, 1e-6, &format!("{label} p[{j}]"));
        let (c_lo, c_hi) = cell_ci_finite(&params.rows[j][4]);
        assert_approx_eq(c_lo, lo[j], tol, tol, &format!("{label} ci_lo[{j}]"));
        assert_approx_eq(c_hi, hi[j], tol, tol, &format!("{label} ci_hi[{j}]"));
    }
    assert_approx_eq(scalar(res, "R squared"), f64_at(oracle, "r_squared"), tol, tol, &format!("{label} R^2"));
    assert_approx_eq(scalar(res, "Adjusted R squared"), f64_at(oracle, "adj_r_squared"), tol, tol, &format!("{label} adj R^2"));
    assert_approx_eq(scalar(res, "Residual SD (Sy.x)"), f64_at(oracle, "sigma"), tol, tol, &format!("{label} sigma"));
    assert_approx_eq(scalar(res, "df residual"), f64_at(oracle, "df_residual"), 1e-12, 1e-12, &format!("{label} df_resid"));
    assert_approx_eq(scalar(res, "AIC"), f64_at(oracle, "aic"), tol, tol, &format!("{label} AIC"));
    assert_approx_eq(scalar(res, "AICc"), f64_at(oracle, "aicc"), tol, tol, &format!("{label} AICc"));
}

