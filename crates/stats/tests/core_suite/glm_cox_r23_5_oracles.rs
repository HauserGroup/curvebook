    assert_approx_eq(scalar(res, "Likelihood ratio chi2"), f64_at(oracle, "lr_chi2"), 1e-7, 1e-7, &format!("{label} lr_chi2"));
    assert_approx_eq(scalar(res, "Likelihood ratio P"), f64_at(oracle, "lr_p"), 1e-7, 1e-6, &format!("{label} lr_p"));
    assert_approx_eq(scalar(res, "AIC"), f64_at(oracle, "aic"), 1e-7, 1e-7, &format!("{label} aic"));
    assert_approx_eq(scalar(res, "AICc"), f64_at(oracle, "aicc_by_events"), 1e-7, 1e-7, &format!("{label} aicc"));
