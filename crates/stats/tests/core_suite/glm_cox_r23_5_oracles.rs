fn make_cox_oracle_sheet(cox_km: &JVal) -> DataSheet {
    let data = cox_km.get("data");
    let times = json_f64_vec(data.get("time"));
    let status = json_f64_vec(data.get("status"));
    let arm = json_str_vec(data.get("arm"));
    let biomarker = json_f64_vec(data.get("biomarker"));
    let age = json_f64_vec(data.get("age"));
    let n = times.len();

    let mut mv = MultipleVariablesTable::new(5, n).unwrap();
    mv.variables[0].title = String::from("time");
    mv.variables[1].title = String::from("status");
    mv.variables[2].title = String::from("arm");
    mv.variables[2].lock_role(VariableRole::Categorical);
    mv.variables[2].level_order = explicit_levels(&["Ctrl", "Drug"]);
    mv.variables[3].title = String::from("biomarker");
    mv.variables[4].title = String::from("age");
    for r in 0..n {
        mv.variables[0].cells[r] = Cell::number(times[r]);
        mv.variables[1].cells[r] = Cell::number(status[r]);
        mv.variables[2].cells[r] = Cell::text(arm[r].as_str());
        mv.variables[3].cells[r] = Cell::number(biomarker[r]);
        mv.variables[4].cells[r] = Cell::number(age[r]);
    }
    DataSheet::new(SheetId::new("cox-r235"), "cox-r235", TableArchetype::MultipleVariables(mv)).unwrap()
}

