    assert_approx_eq(scalar(&res_wald, "AIC"), f64_at(red_o, "aic"), 1e-7, 1e-7, "logit aic");
    assert_approx_eq(scalar(&res_wald, "AICc"), f64_at(red_o, "aicc"), 1e-7, 1e-7, "logit aicc");
    assert_approx_eq(scalar(&res_wald, "Tjur R squared"), f64_at(red_o, "tjur_r2"), 1e-7, 1e-7, "logit tjur");
