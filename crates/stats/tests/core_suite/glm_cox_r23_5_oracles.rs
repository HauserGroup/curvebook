    let se_hr = json_f64_vec(oracle.get("se_hr_delta"));
    let hr_lo = json_f64_vec(oracle.get("hr_wald_ci95_lo"));
    let hr_hi = json_f64_vec(oracle.get("hr_wald_ci95_hi"));
