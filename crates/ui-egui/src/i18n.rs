//! Supports English (`en`) and all eight Tier-1 scientific locales (`de`, `es`, `fr`, `ja`,
//! `ko`, `pt-BR`, `zh-CN`, `zh-TW`), integrating with [`lumencraft_text::LocaleNumberPolicy`] and
//! [`lumencraft_format::CsvOptions`].

