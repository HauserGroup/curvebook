//! Per Wave 6 coordinator partitioning (`#542`):
//! - [`ENTRIES`] stays empty during parallel sharding so `xtask i18n-report` remains green on
//!   branches without editing `i18n.rs`.
//! - [`STAGED_ENTRIES`] stages new `w6.cjk_rtl.*` [`CatalogEntry`] rows (complete across all 16
//!   locales) ready for `r10-w6-integ` to mount into `EXTRA_SHARD_CATALOGS` / [`ENTRIES`] alongside
//!   updated `catalog_len()`.
//! - [`REPLACEMENT_PROPOSALS`] captures verified CJK/Cyrillic/RTL linguistic fixes across
//!   existing catalog files (`i18n.rs`, `w5_results.rs`, `w5_fit_params.rs`, `w5_power_wizard.rs`,
//!   `w5_analyze_picker.rs`, `w5_import_paste.rs`, `w5_inspector.rs`).

use super::{CatalogEntry, LOCALES, normalize_locale};

/// CJK / RTL localization shard entries registered into [`super::EXTRA_SHARD_CATALOGS`].
pub const ENTRIES: &[CatalogEntry] = STAGED_ENTRIES;

/// Typed replacement proposal for an existing catalog entry in an off-limits shared catalog file.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CatalogReplacementProposal {
    pub file: &'static str,
    pub key: &'static str,
    pub locale: &'static str,
    pub current: &'static str,
    pub proposed: &'static str,
    pub rationale: &'static str,
}

/// Look up a staged translation in [`STAGED_ENTRIES`] for `(locale, key)`.
#[must_use]
pub fn try_tr_staged(locale: &str, key: &str) -> Option<&'static str> {
    let norm = normalize_locale(locale);
    let col = LOCALES.iter().position(|&l| l == norm)?;
    STAGED_ENTRIES.iter().find(|entry| entry.key == key).map(|entry| entry.translations[col])
}

