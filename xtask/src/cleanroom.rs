    fn zip_bytes(entries: &[(&str, &[u8])]) -> Vec<u8> {
        let mut zw = ZipWriter::new();
        for &(name, body) in entries {
            zw.add_file(name, body.to_vec()).unwrap();
        }
        zw.finish().unwrap()
    }

    #[test]
