#[derive(Debug, PartialEq, Eq)]
pub struct CleanroomHit {
    pub path: String,
    pub line: usize,
    pub signature: &'static str,
}

#[derive(Clone, Copy)]
enum Boundary {
    None,
    Alnum,
    NotIdent,
}

pub fn run(root: &Path) -> Result<(), String> {
    let files = crate::repo_files(root)?;
    let mut hits = scan(root, &files);
    let web_pkg = root.join("packaging/web");
    if web_pkg.exists() {
        hits.extend(scan_dist_artefacts(&web_pkg)?);
    }
    let dist_dir = root.join("dist");
    let dist_counts = if dist_dir.exists() {
        let (dist_files, dist_entries, dist_hits) = scan_dist_artefacts_with_stats(&dist_dir)?;
        hits.extend(dist_hits);
        Some((dist_files, dist_entries))
    } else {
        None
    };
    if hits.is_empty() {
        if let Some((dist_files, dist_entries)) = dist_counts {
            println!(
                "cleanroom: no vendor copyright notices or vendor-created fixtures found across {} tracked files and {dist_files} dist/ files ({dist_entries} archive entries)",
                files.len()
            );
        } else {
            println!("cleanroom: no vendor copyright notices or vendor-created fixtures found across {} tracked files", files.len());
        }
        return Ok(());
    }
    let formatted: Vec<String> = hits.iter().map(|h| format!("{}:{}: matched `{}`", h.path, h.line, h.signature)).collect();
    Err(format!("{} clean-room violation(s) found:\n  {}", hits.len(), formatted.join("\n  ")))
}

#[must_use]
pub fn scan(root: &Path, files: &[String]) -> Vec<CleanroomHit> {
    let mut hits = Vec::new();
    let mut archive_entries = 0usize;
    for path in files {
        if should_skip(path) {
            continue;
        }
        let norm = path.replace('\\', "/");
        if norm == "plan/prism" || norm.starts_with("plan/prism/") {
            hits.push(CleanroomHit { path: path.clone(), line: 1, signature: "committed plan/prism reference directory" });
            continue;
        }
        let Ok(bytes) = std::fs::read(root.join(path)) else {
            hits.push(CleanroomHit { path: path.clone(), line: 1, signature: "unreadable file" });
            continue;
        };
        scan_bytes_recursive(path, &bytes, 0, false, &mut archive_entries, &mut hits);
    }
    hits
}

/// Scan a standalone release compliance payload (`SHA256SUMS.txt`, `THIRD-PARTY-LICENSES.html`,
/// or `.zsync`) for vendor copyright notices and creator tags.
#[must_use]
pub(crate) fn scan_compliance_bytes(display_path: &str, bytes: &[u8]) -> Vec<CleanroomHit> {
    let mut archive_entries = 0usize;
    let mut hits = Vec::new();
    scan_bytes_recursive(display_path, bytes, 0, true, &mut archive_entries, &mut hits);
    hits
}

/// Recursively scan all assembled artefacts under `dist_dir` (including nested ZIP/`.curvebook`/`.prism`/`.pzf`
/// archives, HTML, manifests, UTF-16 payloads, and even mistakenly bundled audit files), never following symlinks.
pub fn scan_dist_artefacts(dist_dir: &Path) -> Result<Vec<CleanroomHit>, String> {
    let (_, _, hits) = scan_dist_artefacts_with_stats(dist_dir)?;
    Ok(hits)
}

/// Recursively scan all assembled artefacts under `dist_dir`, returning `(file_count, archive_entry_count, hits)`.
pub fn scan_dist_artefacts_with_stats(dist_dir: &Path) -> Result<(usize, usize, Vec<CleanroomHit>), String> {
    if !dist_dir.exists() {
        return Err(format!("dist directory `{}` does not exist", dist_dir.display()));
    }
    let mut rel_files = Vec::new();
    collect_dist_files(dist_dir, dist_dir, &mut rel_files)?;
    rel_files.sort();
    let file_count = rel_files.len();
    let mut archive_entries = 0usize;
    let mut hits = Vec::new();
    for rel in rel_files {
        let norm = rel.replace('\\', "/");
        if norm == "plan/prism" || norm.starts_with("plan/prism/") {
            hits.push(CleanroomHit { path: rel, line: 1, signature: "bundled plan/prism reference directory" });
            continue;
        }
        let Ok(bytes) = std::fs::read(dist_dir.join(&rel)) else {
            hits.push(CleanroomHit { path: rel, line: 1, signature: "unreadable file" });
            continue;
        };
        scan_bytes_recursive(&rel, &bytes, 0, true, &mut archive_entries, &mut hits);
    }
    Ok((file_count, archive_entries, hits))
}

fn collect_dist_files(root: &Path, dir: &Path, out: &mut Vec<String>) -> Result<(), String> {
    let entries = std::fs::read_dir(dir).map_err(|e| format!("read_dir {}: {e}", dir.display()))?;
    let mut paths = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|e| format!("dir entry under {}: {e}", dir.display()))?;
        paths.push(entry.path());
    }
    paths.sort();
    for path in paths {
        let meta = std::fs::symlink_metadata(&path).map_err(|e| format!("stat {}: {e}", path.display()))?;
        if meta.file_type().is_symlink() {
            continue;
        }
        if meta.is_dir() {
            collect_dist_files(root, &path, out)?;
        } else if meta.is_file() {
            let rel = path.strip_prefix(root).map_err(|e| format!("strip prefix {}: {e}", path.display()))?;
            out.push(rel.to_string_lossy().replace('\\', "/"));
        }
    }
    Ok(())
}

fn should_skip(path: &str) -> bool {
    let norm = path.replace('\\', "/");
    let trimmed = norm.strip_prefix("./").unwrap_or(&norm);
    trimmed == SELF
        || trimmed == "docs/audit"
        || trimmed.starts_with(AUDIT_DIR_PREFIX)
        || trimmed == "docs/history/audit"
        || trimmed.starts_with(HISTORY_AUDIT_DIR_PREFIX)
}

fn has_extension_ci(path: &str, exts: &[&str]) -> bool {
    let Some(ext) = Path::new(path).extension().and_then(|e| e.to_str()) else {
        return false;
    };
    exts.iter().any(|candidate| ext.eq_ignore_ascii_case(candidate))
}

fn scan_bytes_recursive(
    display_path: &str,
    bytes: &[u8],
    depth: usize,
    allow_packaged: bool,
    archive_entries: &mut usize,
    hits: &mut Vec<CleanroomHit>,
) {
    let is_vendor_archive = has_extension_ci(display_path, &["prism", "pzf"]);
    let is_zip = bytes.starts_with(b"PK\x03\x04") || bytes.starts_with(b"PK\x05\x06");

    if is_vendor_archive || is_zip {
        if depth >= MAX_ARCHIVE_DEPTH {
            if is_vendor_archive {
                hits.push(CleanroomHit { path: display_path.to_owned(), line: 1, signature: "nested archive depth exceeded" });
            }
            return;
        }
        if let Ok(archive) = ZipArchive::from_bytes_with_limits(bytes, CLEANROOM_ZIP_LIMITS) {
            for (entry_name, entry_bytes) in archive.iter() {
                *archive_entries += 1;
                let entry_path = format!("{display_path}!{entry_name}");
                let mut name_seen = HashSet::new();
                scan_text(&entry_path, entry_name, allow_packaged, hits, &mut name_seen);
                scan_bytes_recursive(&entry_path, entry_bytes, depth + 1, allow_packaged, archive_entries, hits);
            }
            return;
        }
        let before = hits.len();
        scan_text_bytes(display_path, bytes, allow_packaged, hits);
        if is_vendor_archive && hits.len() == before {
            hits.push(CleanroomHit { path: display_path.to_owned(), line: 1, signature: "uninspectable .prism/.pzf archive" });
        }
        return;
    }

    scan_text_bytes(display_path, bytes, allow_packaged, hits);
}

fn scan_text_bytes(display_path: &str, bytes: &[u8], allow_packaged: bool, hits: &mut Vec<CleanroomHit>) {
    let mut seen_lines = HashSet::new();
    if bytes.starts_with(&[0xFF, 0xFE]) {
        let decoded = decode_utf16(bytes.get(2..).unwrap_or_default(), true);
        scan_text(display_path, &decoded, allow_packaged, hits, &mut seen_lines);
        return;
    }
    if bytes.starts_with(&[0xFE, 0xFF]) {
        let decoded = decode_utf16(bytes.get(2..).unwrap_or_default(), false);
        scan_text(display_path, &decoded, allow_packaged, hits, &mut seen_lines);
        return;
    }
    if let Some(stripped) = bytes.strip_prefix(&[0xEF, 0xBB, 0xBF]) {
        let text = String::from_utf8_lossy(stripped);
        scan_text(display_path, &text, allow_packaged, hits, &mut seen_lines);
        return;
    }
    if let Some(little_endian) = detect_bomless_utf16(bytes) {
        let decoded = decode_utf16(bytes, little_endian);
        scan_text(display_path, &decoded, allow_packaged, hits, &mut seen_lines);
    }
    let text = String::from_utf8_lossy(bytes);
    scan_text(display_path, &text, allow_packaged, hits, &mut seen_lines);
}

fn detect_bomless_utf16(bytes: &[u8]) -> Option<bool> {
    if bytes.len() < 8 || !bytes.contains(&0) {
        return None;
    }
    let mut le_ascii = 0usize;
    let mut be_ascii = 0usize;
    let (pairs, _) = bytes.as_chunks::<2>();
    let total_pairs = pairs.len();
    for &[a, b] in pairs {
        if a != 0 && (a.is_ascii_graphic() || a.is_ascii_whitespace()) && b == 0 {
            le_ascii += 1;
        } else if a == 0 && b != 0 && (b.is_ascii_graphic() || b.is_ascii_whitespace()) {
            be_ascii += 1;
        }
    }
    if le_ascii >= 4 && le_ascii * 4 >= total_pairs && le_ascii > be_ascii.saturating_mul(2) {
        Some(true)
    } else if be_ascii >= 4 && be_ascii * 4 >= total_pairs && be_ascii > le_ascii.saturating_mul(2) {
        Some(false)
    } else {
        None
    }
}

fn decode_utf16(bytes: &[u8], little_endian: bool) -> String {
    let (pairs, remainder) = bytes.as_chunks::<2>();
    let units = pairs.iter().map(|&arr| if little_endian { u16::from_le_bytes(arr) } else { u16::from_be_bytes(arr) });
    let mut out = String::with_capacity(pairs.len());
    for ch in char::decode_utf16(units) {
        out.push(ch.unwrap_or('\u{FFFD}'));
    }
    if !remainder.is_empty() {
        out.push('\u{FFFD}');
    }
    out
}

fn compute_attributed_section_lines(display_path: &str, text: &str, allow_packaged: bool) -> Vec<bool> {
    if !crate::brands::is_attribution_or_notice_path(display_path, allow_packaged) {
        return Vec::new();
    }
    let mut flags = Vec::new();
    let mut in_attributed_source = false;
    for line in text.lines() {
        if crate::brands::is_attributed_source_section_heading(line) {
            in_attributed_source = true;
        } else if crate::brands::closes_attributed_source_section(line) {
            in_attributed_source = false;
        }
        flags.push(in_attributed_source);
    }
    flags
}

fn line_forbids_vectorcraft(display_path: &str, line_idx: usize, attributed_lines: &[bool]) -> bool {
    if crate::brands::is_crates_or_apps_path(display_path) {
        return true;
    }
    if crate::brands::is_legal_policy_doc_path(display_path) {
        return false;
    }
    !attributed_lines.get(line_idx).copied().unwrap_or(false)
}

fn scan_text(display_path: &str, text: &str, allow_packaged: bool, hits: &mut Vec<CleanroomHit>, seen_lines: &mut HashSet<usize>) {
    let masked = crate::brands::mask_attributed_upstream_url(display_path, text, allow_packaged);
    let attributed_lines = compute_attributed_section_lines(display_path, &masked, allow_packaged);
    let normalized: Vec<String> = masked.lines().map(normalize_line).collect();
    for (idx, norm) in normalized.iter().enumerate() {
        let line_no = idx + 1;
        let check_vectorcraft = line_forbids_vectorcraft(display_path, idx, &attributed_lines);
        if let Some(sig) = match_single_line(norm, check_vectorcraft)
            && seen_lines.insert(line_no)
        {
            hits.push(CleanroomHit { path: display_path.to_owned(), line: line_no, signature: sig });
        }
    }
    for idx in 0..normalized.len().saturating_sub(1) {
        let line_no = idx + 1;
        if seen_lines.contains(&line_no) || seen_lines.contains(&(line_no + 1)) {
            continue;
        }
        if let (Some(first), Some(second)) = (normalized.get(idx), normalized.get(idx + 1)) {
            let joined = format!("{first} {second}");
            let check_vectorcraft =
                line_forbids_vectorcraft(display_path, idx, &attributed_lines) || line_forbids_vectorcraft(display_path, idx + 1, &attributed_lines);
            if let Some(sig) = match_created_or_notice(&joined, MAX_ADJACENT_LINE_GAP, check_vectorcraft)
                && seen_lines.insert(line_no)
            {
                hits.push(CleanroomHit { path: display_path.to_owned(), line: line_no, signature: sig });
            }
        }
    }
}

fn normalize_line(line: &str) -> String {
    let mut out = String::with_capacity(line.len());
    let mut prev_space = false;
    for ch in line.chars() {
        if ch.is_whitespace() {
            if !prev_space {
                out.push(' ');
                prev_space = true;
            }
        } else {
            out.push(ch.to_ascii_lowercase());
            prev_space = false;
        }
    }
    out
}

fn match_single_line(norm: &str, check_vectorcraft: bool) -> Option<&'static str> {
    if norm.contains("<graphpadprismfile") {
        return Some("<GraphPadPrismFile");
    }
    match_created_or_notice(norm, MAX_SAME_LINE_GAP, check_vectorcraft)
}

fn match_created_or_notice(norm: &str, max_gap: usize, check_vectorcraft: bool) -> Option<&'static str> {
    for prefix in CREATOR_PREFIXES {
        for &(vendor, sig) in CREATOR_VENDORS {
            if has_creator_phrase(norm, prefix, vendor) {
                return Some(sig);
            }
        }
        if check_vectorcraft && has_creator_phrase(norm, prefix, crate::brands::ADAPTED_UPSTREAM_BRAND) {
            return Some("adapted upstream creator notice (vectorcraft)");
        }
    }
    has_nearby_vendor_notice(norm, max_gap, check_vectorcraft)
}

fn has_creator_phrase(norm: &str, prefix: &str, vendor: &str) -> bool {
    let phrase = format!("{prefix} {vendor}");
    let mut created = Vec::new();
    collect_spans(norm, &phrase, Boundary::Alnum, Boundary::Alnum, &mut created);
    !created.is_empty()
}

fn has_nearby_vendor_notice(norm: &str, max_gap: usize, check_vectorcraft: bool) -> Option<&'static str> {
    let indicators = find_indicator_spans(norm);
    if indicators.is_empty() {
        return None;
    }
    for &(vendor, sig) in VENDOR_SIGNATURES {
        let mut vendor_spans = Vec::new();
        collect_spans(norm, vendor, Boundary::Alnum, Boundary::Alnum, &mut vendor_spans);
        if has_nearby_pair(&vendor_spans, &indicators, max_gap) {
            return Some(sig);
        }
    }
    if check_vectorcraft {
        let mut vendor_spans = Vec::new();
        collect_spans(norm, crate::brands::ADAPTED_UPSTREAM_BRAND, Boundary::Alnum, Boundary::Alnum, &mut vendor_spans);
        if has_nearby_pair(&vendor_spans, &indicators, max_gap) {
            return Some("adapted upstream copyright notice (vectorcraft)");
        }
    }
    None
}

fn find_indicator_spans(norm: &str) -> Vec<(usize, usize)> {
    let mut out = Vec::new();
    collect_spans(norm, "copyright", Boundary::Alnum, Boundary::Alnum, &mut out);
    collect_spans(norm, "all rights reserved", Boundary::Alnum, Boundary::Alnum, &mut out);
    collect_spans(norm, "(c)", Boundary::NotIdent, Boundary::None, &mut out);
    collect_spans(norm, "©", Boundary::None, Boundary::None, &mut out);
    collect_spans(norm, "&copy;", Boundary::None, Boundary::None, &mut out);
    collect_spans(norm, "&#169;", Boundary::None, Boundary::None, &mut out);
    collect_spans(norm, "&#xa9;", Boundary::None, Boundary::None, &mut out);
    collect_spans(norm, "&#x00a9;", Boundary::None, Boundary::None, &mut out);
    out
}

fn has_nearby_pair(a: &[(usize, usize)], b: &[(usize, usize)], max_gap: usize) -> bool {
    for &(a_start, a_end) in a {
        for &(b_start, b_end) in b {
            let gap = if a_end <= b_start { b_start - a_end } else { a_start.saturating_sub(b_end) };
            if gap <= max_gap {
                return true;
            }
        }
    }
    false
}

fn boundary_ok(byte: Option<u8>, rule: Boundary) -> bool {
    match (rule, byte) {
        (Boundary::None, _) | (_, None) => true,
        (Boundary::Alnum, Some(b)) => !b.is_ascii_alphanumeric(),
        (Boundary::NotIdent, Some(b)) => !(b.is_ascii_alphanumeric() || b == b'_'),
    }
}

fn collect_spans(haystack: &str, needle: &str, left: Boundary, right: Boundary, out: &mut Vec<(usize, usize)>) {
    let bytes = haystack.as_bytes();
    let nlen = needle.len();
    let mut start = 0;
    while let Some(slice) = haystack.get(start..)
        && let Some(rel) = slice.find(needle)
    {
        let pos = start + rel;
        let end = pos + nlen;
        let prev = pos.checked_sub(1).and_then(|i| bytes.get(i).copied());
        let next = bytes.get(end).copied();
        if boundary_ok(prev, left) && boundary_ok(next, right) {
            out.push((pos, end));
        }
        start = pos.saturating_add(1);
        while start < bytes.len() && !haystack.is_char_boundary(start) {
            start += 1;
        }
    }
}

